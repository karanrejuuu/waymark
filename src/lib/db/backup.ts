import { db } from "./dexie";

export interface WaymarkBackup {
  version: number;
  exportedAt: string;
  app: "Waymark FMCG";
  counts: Record<string, number>;
  data: {
    shops: any[];
    shop_products: any[];
    regions: any[];
    products: any[];
    godowns: any[];
    deliveries: any[];
    payments: any[];
    organisations: any[];
    profiles: any[];
    invoices?: any[];
    company_profiles?: any[];
  };
}

export async function createDatabaseBackup(): Promise<WaymarkBackup> {
  const [
    shops,
    shop_products,
    regions,
    products,
    godowns,
    deliveries,
    payments,
    organisations,
    profiles,
    invoices,
    company_profiles,
  ] = await Promise.all([
    db.shops.toArray(),
    db.shop_products.toArray(),
    db.regions.toArray(),
    db.products.toArray(),
    db.godowns.toArray(),
    db.deliveries.toArray(),
    db.payments.toArray(),
    db.organisations.toArray(),
    db.profiles.toArray(),
    db.invoices.toArray(),
    db.company_profiles.toArray(),
  ]);

  const backup: WaymarkBackup = {
    version: 3,
    exportedAt: new Date().toISOString(),
    app: "Waymark FMCG",
    counts: {
      shops: shops.length,
      shop_products: shop_products.length,
      regions: regions.length,
      products: products.length,
      deliveries: deliveries.length,
      payments: payments.length,
      invoices: invoices.length,
      company_profiles: company_profiles.length,
    },
    data: {
      shops,
      shop_products,
      regions,
      products,
      godowns,
      deliveries,
      payments,
      organisations,
      profiles,
      invoices,
      company_profiles,
    },
  };

  return backup;
}

export async function downloadDatabaseBackup(): Promise<void> {
  const backup = await createDatabaseBackup();
  const jsonString = JSON.stringify(backup, null, 2);
  const blob = new Blob([jsonString], { type: "application/json" });
  const url = URL.createObjectURL(blob);
  const now = new Date().toISOString().slice(0, 10);

  const a = document.createElement("a");
  a.href = url;
  a.download = `waymark-backup-${now}.json`;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

export async function restoreDatabaseBackup(
  backupJson: string
): Promise<{ success: boolean; message: string; restoredCounts?: Record<string, number> }> {
  try {
    const parsed = JSON.parse(backupJson) as WaymarkBackup;

    if (!parsed || parsed.app !== "Waymark FMCG" || !parsed.data) {
      return { success: false, message: "Invalid backup format. Ensure file was generated by Waymark." };
    }

    const { data } = parsed;

    await db.transaction(
      "rw",
      [
        db.shops,
        db.shop_products,
        db.regions,
        db.products,
        db.godowns,
        db.deliveries,
        db.payments,
        db.organisations,
        db.profiles,
        db.invoices,
        db.company_profiles,
      ],
      async () => {
        if (data.regions?.length) await db.regions.bulkPut(data.regions);
        if (data.products?.length) await db.products.bulkPut(data.products);
        if (data.shops?.length) await db.shops.bulkPut(data.shops);
        if (data.shop_products?.length) await db.shop_products.bulkPut(data.shop_products);
        if (data.godowns?.length) await db.godowns.bulkPut(data.godowns);
        if (data.deliveries?.length) await db.deliveries.bulkPut(data.deliveries);
        if (data.payments?.length) await db.payments.bulkPut(data.payments);
        if (data.organisations?.length) await db.organisations.bulkPut(data.organisations);
        if (data.profiles?.length) await db.profiles.bulkPut(data.profiles);
        if (data.invoices?.length) await db.invoices.bulkPut(data.invoices);
        if (data.company_profiles?.length) await db.company_profiles.bulkPut(data.company_profiles);
      }
    );

    return {
      success: true,
      message: `Successfully restored database!`,
      restoredCounts: {
        shops: data.shops?.length || 0,
        regions: data.regions?.length || 0,
        products: data.products?.length || 0,
        deliveries: data.deliveries?.length || 0,
        payments: data.payments?.length || 0,
        invoices: data.invoices?.length || 0,
      },
    };
  } catch (err: any) {
    return { success: false, message: `Restore failed: ${err.message || String(err)}` };
  }
}
